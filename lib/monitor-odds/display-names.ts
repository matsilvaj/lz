export function normalizeOddsDisplayKey(value: string | null | undefined) {
  return String(value ?? "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim()
    .toLowerCase()
    .replace(/['’]/g, "")
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export function formatCompetitionName(
  value: string,
  country?: string | null,
) {
  const trimmed = value.trim();
  const key = normalizeOddsDisplayKey(trimmed);
  const translated = competitionNameTranslations[key];

  if (translated) {
    return translated;
  }

  if (key.startsWith("world-cup-qualification")) {
    return "Eliminatórias da Copa do Mundo";
  }

  if (key.startsWith("fifa-world-cup-qualification")) {
    return "Eliminatórias da Copa do Mundo";
  }

  if (key === "world-cup" || key === "fifa-world-cup") {
    return "Copa do Mundo";
  }

  if (normalizeOddsDisplayKey(country) === "world" && key === "friendlies") {
    return "Amistoso Internacional";
  }

  return trimmed;
}

export function formatNationalTeamName(value: string) {
  const trimmed = value.trim();
  const direct = nationalTeamNameTranslations[normalizeOddsDisplayKey(trimmed)];

  if (direct) {
    return direct;
  }

  const ageMatch = trimmed.match(/^(.*?)\s+U(\d{2})$/i);

  if (ageMatch) {
    const base = nationalTeamNameTranslations[normalizeOddsDisplayKey(ageMatch[1])];
    return base ? `${base} Sub-${ageMatch[2]}` : trimmed;
  }

  const womenMatch = trimmed.match(/^(.*?)\s+(?:W|Women|\(W\))$/i);

  if (womenMatch) {
    const base = nationalTeamNameTranslations[normalizeOddsDisplayKey(womenMatch[1])];
    return base ? `${base} Feminino` : trimmed;
  }

  const olympicMatch = trimmed.match(/^(.*?)\s+Olympic$/i);

  if (olympicMatch) {
    const base = nationalTeamNameTranslations[normalizeOddsDisplayKey(olympicMatch[1])];
    return base ? `${base} Olímpico` : trimmed;
  }

  return trimmed;
}

export function formatLeagueCountryName(value: string | null | undefined) {
  if (!value) return "";

  const trimmed = value.trim();
  return nationalTeamNameTranslations[normalizeOddsDisplayKey(trimmed)] ?? trimmed;
}
